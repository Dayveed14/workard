import { Fragment } from 'react';
import Logo from './Logo.jsx';
import { formatMoney, monthLabel } from '../utils/format.js';
import './PayslipDocument.css';

// A printable payslip (Print → Save as PDF). `p` is a payroll item from the API.
export default function PayslipDocument({ p }) {
  const n = (v) => Number(v || 0);
  const earnings = [
    ['Basic salary', p.basic_kobo],
    ['Housing allowance', p.housing_kobo],
    ['Transport allowance', p.transport_kobo],
    ['Other allowances', p.allowances_kobo],
    ['Bonus', p.bonus_kobo],
  ].filter(([, v]) => n(v) > 0);

  const deductions = [
    ['PAYE tax', p.paye_kobo],
    ['Pension (employee)', p.pension_employee_kobo],
    ['National Housing Fund', p.nhf_kobo],
    ['Other deductions', p.other_deductions_kobo],
    ['One-off deduction', p.one_off_deduction_kobo],
  ].filter(([, v]) => n(v) > 0);

  const totalDeductions = deductions.reduce((s, [, v]) => s + n(v), 0);

  return (
    <article className="payslip">
      <header className="payslip__top">
        <div>
          <h2>{p.organization_name}</h2>
          <span className="payslip__label">Payslip</span>
          <strong className="payslip__period">{monthLabel(p.period)}</strong>
        </div>
        <dl className="payslip__who">
          <dt>Employee</dt>
          <dd>{p.first_name} {p.last_name}</dd>
          {p.staff_id && (<><dt>Staff ID</dt><dd>{p.staff_id}</dd></>)}
          {p.job_title && (<><dt>Job title</dt><dd>{p.job_title}</dd></>)}
          {p.department_name && (<><dt>Department</dt><dd>{p.department_name}</dd></>)}
          {p.pension_pin && (<><dt>Pension PIN</dt><dd>{p.pension_pin}</dd></>)}
          {p.tax_id && (<><dt>Tax ID</dt><dd>{p.tax_id}</dd></>)}
        </dl>
      </header>

      {(n(p.proration_kobo) > 0 || p.unpaid_leave_days > 0) && (
        <p className="payslip__note">
          Paid for {p.days_payable} of {p.days_in_period} working days
          {p.unpaid_leave_days > 0 && ` (${p.unpaid_leave_days} day(s) unpaid leave)`}
          {' '}— {formatMoney(p.proration_kobo)} less than a full month.
        </p>
      )}

      <div className="payslip__cols">
        <section>
          <h3>Earnings</h3>
          <dl>
            {earnings.map(([label, v]) => (
              <Fragment key={label}><dt>{label}</dt><dd>{formatMoney(v)}</dd></Fragment>
            ))}
            <dt className="payslip__sum">Gross pay</dt>
            <dd className="payslip__sum">{formatMoney(p.gross_kobo)}</dd>
          </dl>
        </section>
        <section>
          <h3>Deductions</h3>
          <dl>
            {deductions.length === 0 && (<><dt>None</dt><dd>—</dd></>)}
            {deductions.map(([label, v]) => (
              <Fragment key={label}><dt>{label}</dt><dd>{formatMoney(v)}</dd></Fragment>
            ))}
            <dt className="payslip__sum">Total deductions</dt>
            <dd className="payslip__sum">{formatMoney(totalDeductions)}</dd>
          </dl>
        </section>
      </div>

      <div className="payslip__net">
        <span>Net pay</span>
        <strong>{formatMoney(p.net_kobo)}</strong>
      </div>

      <footer className="payslip__foot">
        <span>
          Paid to {p.account_name || `${p.first_name} ${p.last_name}`}
          {p.bank_name && ` · ${p.bank_name}`}
          {p.account_number && ` · ****${p.account_number.slice(-4)}`}
        </span>
        {n(p.pension_employer_kobo) > 0 && (
          <span>Your employer also paid {formatMoney(p.pension_employer_kobo)} into your pension.</span>
        )}
      </footer>
      <p className="payslip__powered">
        Generated by <Logo size={12} />
      </p>
    </article>
  );
}
